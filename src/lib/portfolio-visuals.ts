export type VisualNode = {
  id: string;
  label: string;
  detail?: string;
  x: number;
  y: number;
  kind?: "primary" | "plain";
};
export type VisualEdge = { from: string; to: string };
type VisualBase = {
  title: string;
  architecture: string;
  impact?: { value: string; label: string }[];
};
export type GraphVisual = VisualBase & {
  type: "graph";
  nodes: VisualNode[];
  edges: VisualEdge[];
};
export type NodeSide = "l" | "r" | "t" | "b";
export type SystemLane = {
  id: string;
  label: string;
  x: number;
  width: number;
};
// Detail lines split on \n; `short` replaces the label in compact gallery cards.
export type SystemNode = VisualNode & {
  lane: string;
  width?: number;
  height?: number;
  short?: string;
};
export type SystemEdge = VisualEdge & {
  id?: string;
  kind?: "request" | "async" | "poll" | "asset" | "ops";
  label?: string;
  duplex?: boolean;
  fromSide?: NodeSide;
  toSide?: NodeSide;
  d?: string;
  labelAt?: Point;
};
// `reverse` lists step edges whose packets travel from `to` back to `from`, e.g. a response.
export type SystemStep = {
  id: string;
  label: string;
  detail: string;
  nodes: string[];
  edges: string[];
  reverse?: string[];
};
export type SystemVisual = VisualBase & {
  type: "system";
  journey: string;
  width: number;
  height: number;
  lanes: SystemLane[];
  boundary: {
    label: string;
    x: number;
    y: number;
    width: number;
    height: number;
    railY: number;
    railLabel: string;
  };
  nodes: SystemNode[];
  edges: SystemEdge[];
  steps: SystemStep[];
};
export type ProjectVisual = GraphVisual | SystemVisual;
export const edgeKey = (edge: SystemEdge) =>
  edge.id ?? `${edge.from}>${edge.to}`;

